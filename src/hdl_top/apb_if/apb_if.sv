`ifndef APB_IF_INCLUDED_
`define APB_IF_INCLUDED_

//--------------------------------------------------------------------------------------------
// Interface : apb_if
// Declaration of pin level signals for APB interface
//--------------------------------------------------------------------------------------------
interface apb_if (
  input pclk,
  input preset_n
);

  // Import APB package INSIDE the interface
  import apb_global_pkg::*;

  //------------------------------------------------------------------------------------------
  // PSEL
  //------------------------------------------------------------------------------------------
  logic [NO_OF_SLAVES-1:0] pselx;

  //------------------------------------------------------------------------------------------
  // PENABLE
  //------------------------------------------------------------------------------------------
  logic penable;

  //------------------------------------------------------------------------------------------
  // PADDR
  //------------------------------------------------------------------------------------------
  logic [ADDRESS_WIDTH-1:0] paddr;

  //------------------------------------------------------------------------------------------
  // PWRITE
  //------------------------------------------------------------------------------------------
  logic pwrite;

  //------------------------------------------------------------------------------------------
  // PSTRB
  //------------------------------------------------------------------------------------------
  logic [(APB_DATA_WIDTH/8)-1:0] pstrb;

  //------------------------------------------------------------------------------------------
  // PWDATA
  //------------------------------------------------------------------------------------------
  logic [APB_DATA_WIDTH-1:0] pwdata;

  //------------------------------------------------------------------------------------------
  // PREADY
  //------------------------------------------------------------------------------------------
  logic pready;

  //------------------------------------------------------------------------------------------
  // PRDATA
  //------------------------------------------------------------------------------------------
  logic [APB_DATA_WIDTH-1:0] prdata;

  //------------------------------------------------------------------------------------------
  // PSLVERR
  //------------------------------------------------------------------------------------------
  logic pslverr;

  //------------------------------------------------------------------------------------------
  // PPROT
  //------------------------------------------------------------------------------------------
  logic [2:0] pprot;

endinterface : apb_if

`endif
